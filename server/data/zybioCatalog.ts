/**
 * Canonical extract from ZYBIO Price.pdf (unit = USD / kit, typically 10 vials).
 * Yellow PDF rows = custom dosage; still included for completeness.
 */

export type ZybioForm = 'vial' | 'capsule' | 'other';

export type ZybioSku = {
  sku: string;
  specLabel: string;
  /** Nominal wholesale USD from PDF */
  priceUsd: number;
  form?: ZybioForm;
};

export type ZybioFamily = {
  id: string;
  title: string;
  /** Canonical storefront slug (existing or to create) */
  slug: string;
  description: string;
  categories: string[];
  /** Unsplash photo id fallback */
  imagePhotoId: string;
  variants: ZybioSku[];
  /**
   * create = Phase 2 new product
   * merge = Phase 3 add missing variants onto existing slug
   * fix = Phase 1 data-integrity (also merged in Phase 3 for completeness)
   */
  syncMode: 'create' | 'merge' | 'fix';
  /** Optional UK shop name hint for imagery */
  imageHint?: string;
};

